/**
 * Generates src/lib/fallback.js from Backend/src/seed/data.js.
 * The website uses this built-in copy of Aspira's verified content whenever the
 * API/database is unreachable, so pages are never empty.
 * Run: npm run sync-content   (after editing the seed data)
 */
const fs = require('fs');
const path = require('path');
const data = require('../../Backend/src/seed/data.js');

const strip = ({ adminNote, ...rest }) => rest;
const services = data.services.filter((s) => s.status === 'published').map(strip);
const accreditations = data.accreditations.filter((a) => a.published).map((a, i) => ({ _id: `local-acc-${i}`, ...strip(a) }));
const { key, ...settings } = data.settings;
const posts = (data.posts || []).filter((p) => p.status === 'published').map((p, i) => ({ _id: `local-post-${i}`, author: 'Aspira Certifications Team', ...p }));
const resources = (data.resources || []).filter((r) => r.published).map((r, i) => ({ _id: `local-res-${i}`, ...r }));
const policies = (data.policies || []).filter((p) => p.published).map((p, i) => ({ _id: `local-pol-${i}`, ...strip(p) }));

const out = `/* AUTO-GENERATED by scripts/sync-fallback.cjs – do not edit by hand. */
export const FALLBACK_SETTINGS = ${JSON.stringify(settings, null, 2)};
export const FALLBACK_SERVICES = ${JSON.stringify(services, null, 2)};
export const FALLBACK_ACCREDITATIONS = ${JSON.stringify(accreditations, null, 2)};
export const FALLBACK_POSTS = ${JSON.stringify(posts, null, 2)};
export const FALLBACK_RESOURCES = ${JSON.stringify(resources, null, 2)};
export const FALLBACK_POLICIES = ${JSON.stringify(policies, null, 2)};
`;
fs.writeFileSync(path.join(__dirname, '..', 'src', 'lib', 'fallback.js'), out);
console.log(`fallback.js written: ${services.length} services, ${accreditations.length} accreditations, ${posts.length} posts, ${resources.length} resources, ${policies.length} policies`);
